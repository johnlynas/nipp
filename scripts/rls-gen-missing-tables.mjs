/**
 * Phase 2 — reflect tables/enums that `prisma db push` created but the migration chain
 * never contains, and emit idempotent DDL for a new catch-up migration.
 *
 * Drift found on 2026-09-19 (dev nipp_dev):
 *   enums:  NotificationPriority, NotificationScope, CalendarEventType, CalendarRecurrenceFrequency
 *   tables: Team, TeamMember, TeamRole, Calendar, CalendarEvent, Notification
 *
 * Emission uses plain string concatenation (no template literals) for the SQL text —
 * dollar-quoting inside backticks proved unmanageable through editors.
 *
 * Output printed to stdout AND written to /tmp/rls-catchup-ddl.sql (no secrets in it).
 */
import { readFileSync, writeFileSync } from 'node:fs';

for (const line of readFileSync(new URL('../.env', import.meta.url), 'utf8').split('\n')) {
  const m = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim());
  if (!m) continue;
  let v = m[2].trim();
  if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) v = v.slice(1, -1);
  process.env[m[1]] ??= v;
}
const url = new URL(process.env.DATABASE_URL);
const authUrl = 'postgresql://' + url.username + ':' + encodeURIComponent(url.password) + '@' + url.host + url.pathname;

const { default: pg } = await import('pg');
const c = new pg.Client({ connectionString: authUrl });
await c.connect();

const NL = '\n';
let sql = '';
sql += '-- ============================================================' + NL;
sql += '-- Chain catch-up: objects missing from migration history' + NL;
sql += '-- ============================================================' + NL;
sql += '-- The dev database was created with `prisma db push`, so several objects it' + NL;
sql += '-- carries were NEVER present in any migration file; a fresh `migrate deploy`' + NL;
sql += '-- failed (type "NotificationPriority" does not exist at job-scheduler, then' + NL;
sql += '-- six missing tables). This migration reflects the verified dev nipp_dev' + NL;
sql += '-- catalog (2026-09-19) so the chain is self-sufficient for fresh instances.' + NL;
sql += '-- All statements are idempotent - a no-op on existing db-push databases,' + NL;
sql += '-- authoritative on fresh `migrate deploy` runs. Generated by:' + NL;
sql += '--   node scripts/rls-gen-missing-tables.mjs' + NL;
sql += '-- Re-run that script after any schema change touching these objects and diff' + NL;
sql += '-- its output against this migration file (drift check).' + NL;
sql += '-- ============================================================' + NL + NL;

// --- enums (guarded DO blocks) --------------------------------------------
const ENUMS = ['CalendarRecurrenceFrequency', 'CalendarEventType', 'NotificationPriority', 'NotificationScope'];
for (const enumName of ENUMS) {
  const rows = (await c.query(
    "SELECT ev.enumlabel FROM pg_type t" + NL +
    "  JOIN pg_namespace ns ON ns.oid = t.typnamespace" + NL +
    "  JOIN pg_enum ev ON ev.enumtypid = t.oid" + NL +
    " WHERE ns.nspname = 'public' AND lower(t.typname) = $1" + NL +
    ' ORDER BY ev.enumsortorder', [enumName.toLowerCase()]
  )).rows;
  if (rows.length === 0) throw new Error('enum ' + enumName + ' not found in dev db');
  // Enum labels: single-quoted string literals (NEVER bare — on Postgres 16+
  // the real DAILY/WEEKLY labels are reserved keywords and fail unquoted).
  // Type name: double-quoted so the catalog stores the exact Prisma casing,
  // which matches every quoted reference elsewhere in this migration.
  const values = rows.map((x) => "'" + x.enumlabel.replace(/'/g, "''") + "'").join(', ');
  sql += 'DO $ddl$ BEGIN' + NL;
  sql += "  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE lower(typname) = '" + enumName.toLowerCase() + "' AND typtype IN ('e','c')) THEN" + NL;
  sql += '    CREATE TYPE ' + JSON.stringify(enumName) + ' AS ENUM (' + values + ');' + NL;
  sql += '  END IF;' + NL;
  sql += 'END $ddl$;' + NL;
}

// --- tables ----------------------------------------------------------------
// Parent tables before children (FK dependency order).
const TABLES = ['Team', 'Calendar', 'TeamMember', 'TeamRole', 'CalendarEvent', 'Notification'];

const colType = (x) => {
  if (x.data_type === 'USER-DEFINED') return JSON.stringify(x.udt_name); // enums, jsonb
  switch (x.data_type) {
    case 'timestamp without time zone': return 'TIMESTAMP(3)';
    case 'boolean': return 'BOOLEAN';
    case 'integer': return 'INTEGER';
    case 'bigint': return 'BIGINT';
    default: return x.udt_name; // text, uuid, ...
  }
};

for (const t of TABLES) {
  const cols = (await c.query(
    "SELECT column_name, data_type, udt_name, is_nullable, column_default" + NL +
    '  FROM information_schema.columns' + NL +
    " WHERE table_schema='public' AND table_name=$1 ORDER BY ordinal_position", [t]
  )).rows;

  const pks = (await c.query(
    'SELECT a.attname FROM pg_constraint con' + NL +
    '  JOIN pg_class cl ON cl.oid = con.conrelid' + NL +
    '  JOIN pg_namespace ns ON ns.oid = cl.relnamespace' + NL +
    ' CROSS JOIN LATERAL unnest(con.conkey) k(attnum)' + NL +
    '  JOIN pg_attribute a ON a.attrelid = con.conrelid AND a.attnum = k.attnum' + NL +
    " WHERE ns.nspname='public' AND cl.relname=$1 AND con.contype='p'" + NL +
    ' ORDER BY array_position(con.conkey, a.attnum)', [t]
  )).rows;

  const cons = (await c.query(
    "SELECT con.conname, con.contype, fct.relname AS rftable, a2.attname AS rfcol," + NL +
    "       CASE con.confupdtype WHEN 'c' THEN 'CASCADE' WHEN 'n' THEN 'NO ACTION' WHEN 'd' THEN 'SET NULL' WHEN 'r' THEN 'RESTRICT' ELSE 'DEFAULT' END AS updel," + NL +
    "       CASE con.confdeltype WHEN 'c' THEN 'CASCADE' WHEN 'n' THEN 'NO ACTION' WHEN 'd' THEN 'SET NULL' WHEN 'r' THEN 'RESTRICT' ELSE 'DEFAULT' END AS deldel," + NL +
    "       array_to_string(array_agg(a.attname ORDER BY x.ord), ',') AS cols" + NL +
    '  FROM pg_constraint con' + NL +
    '   JOIN pg_class cl ON cl.oid = con.conrelid' + NL +
    '   JOIN pg_namespace ns ON ns.oid = cl.relnamespace' + NL +
    ' CROSS JOIN LATERAL unnest(con.conkey) WITH ORDINALITY x(attnum, ord)' + NL +
    '   JOIN pg_attribute a ON a.attrelid = con.conrelid AND a.attnum = x.attnum' + NL +
    ' LEFT JOIN pg_class fct ON fct.oid = con.confrelid' + NL +
    '   LEFT JOIN LATERAL unnest(con.confkey) WITH ORDINALITY xf(attnum, ord) ON xf.ord = x.ord' + NL +
    '   LEFT JOIN pg_attribute a2 ON a2.attrelid = con.confrelid AND a2.attnum = xf.attnum' + NL +
    " WHERE ns.nspname='public' AND cl.relname=$1 AND con.contype IN ('u','f')" + NL +
    ' GROUP BY con.oid, con.conname, fct.relname, a2.attname, con.confupdtype, con.confdeltype', [t]
  )).rows;

  const idx = (await c.query(
    'SELECT i.relname AS name, pg_get_indexdef(ii.indexrelid) AS def' + NL +
    '  FROM pg_index ii' + NL +
    '   JOIN pg_class tbl ON tbl.oid = ii.indrelid' + NL +
    '   JOIN pg_class i ON i.oid = ii.indexrelid' + NL +
    '   JOIN pg_namespace ns ON ns.oid = tbl.relnamespace' + NL +
    " WHERE ns.nspname='public' AND tbl.relname=$1 AND NOT ii.indisprimary", [t]
  )).rows;

  sql += NL + 'CREATE TABLE IF NOT EXISTS ' + JSON.stringify(t) + ' (' + NL;
  const colDefs = cols.map((x) =>
    '  ' + JSON.stringify(x.column_name) + ' ' + colType(x) +
    (x.column_default ? ' DEFAULT ' + x.column_default : '') +
    (x.is_nullable === 'NO' ? ' NOT NULL' : '')
  );
  const extra = [];
  if (pks.length) extra.push('PRIMARY KEY (' + pks.map((r) => JSON.stringify(r.attname)).join(', ') + ')');
  for (const cc of cons) {
    const colList = cc.cols.split(',').map((x) => JSON.stringify(x.trim())).join(', ');
    if (cc.contype === 'u') extra.push('CONSTRAINT ' + JSON.stringify(cc.conname) + ' UNIQUE (' + colList + ')');
    else {
      const acts = (cc.updel !== 'NO ACTION' ? ' ON UPDATE ' + cc.updel : '') +
                   (cc.deldel !== 'NO ACTION' ? ' ON DELETE ' + cc.deldel : '');
      extra.push('FOREIGN KEY (' + colList + ') REFERENCES ' + JSON.stringify(cc.rftable) + ' (' + JSON.stringify(cc.rfcol) + ')' + acts);
    }
  }
  sql += colDefs.concat(extra).join(',\n');
  sql += NL + ');' + NL;

  for (const i of idx) {
    const def = i.def.replace(' ON public.', ' ON ').replace(/\s+$/, '');
    sql += 'DO $ddl$ BEGIN' + NL;
    sql += "  IF NOT EXISTS (SELECT 1 FROM pg_indexes WHERE indexname='" + i.name + "') THEN" + NL;
    sql += '    ' + def + ';' + NL;
    sql += '  END IF;' + NL;
    sql += 'END $ddl$;' + NL;
  }
}

await c.end();
writeFileSync('/tmp/rls-catchup-ddl.sql', sql);
console.log(sql);
